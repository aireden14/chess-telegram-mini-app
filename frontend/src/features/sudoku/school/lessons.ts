import { LESSON_POSITIONS, LessonPosition } from "./lessonPositions";

/**
 * Программа «Школы судоку»: двадцать уроков от «как читать доску» до Swordfish.
 *
 * Позиции сюда не пишутся руками — они берутся из пулов, собранных
 * `scripts/build-sudoku-lessons.mjs`, по одному приёму на урок. Курсор общий и
 * двигается сверху вниз, поэтому каждая доска попадает ровно в один урок, а
 * ранние уроки получают самые полные и потому самые читаемые позиции.
 */

export interface SudokuLesson {
  id: number;
  title: string;
  /** Короткая метка приёма для списка уроков. */
  tag: string;
  /** Одна строка: что игрок будет уметь после урока. */
  goal: string;
  /** Теория — по абзацу на мысль, читается с телефона. */
  theory: string[];
  /** Разбор: та же механика, но приём уже показан. */
  demo: LessonPosition | null;
  tasks: LessonPosition[];
  /** Показывать ли в клетках кандидатов: без них учатся сканировать, с ними — считать. */
  candidates: boolean;
}

const cursor: Record<string, number> = {};

/** Берёт следующие n позиций приёма. Порядок вызовов и есть порядок уроков. */
function pick(tech: string, n: number): LessonPosition[] {
  const pool = LESSON_POSITIONS[tech] ?? [];
  const start = cursor[tech] ?? 0;
  const slice = pool.slice(start, start + n);
  cursor[tech] = start + slice.length;
  return slice;
}

/** Урок на одном приёме: первая позиция уходит в разбор, остальные — в задачи. */
function lesson(
  id: number,
  tech: string,
  candidates: boolean,
  meta: { title: string; tag: string; goal: string; theory: string[] },
  count = 4,
): SudokuLesson {
  const [demo, ...tasks] = pick(tech, count);
  return { id, ...meta, demo: demo ?? null, tasks, candidates };
}

